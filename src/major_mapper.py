def map_major(raw_value):
    """
    Map a raw major string to one of the CANONICAL values or return None.
    """
    if raw_value is None:
        return None

    s_orig = str(raw_value)
    s = normalize_arabic(s_orig)

    if is_garbage(s):
        return None

    # Remove trailing degree titles or extra ASCII notes
    s = re.sub(r"\b(بكالوريوس|ماجستير|دبلوم|دكتور|دكتوراه|بمستقبل|اتمتة|in|،).*$", "", s).strip()
    s = re.split(r"[A-Za-z]", s)[0].strip()

    if not s:
        return None

    # Exact manual map
    if s in MANUAL_MAP:
        return MANUAL_MAP[s]

    # Substring matching against keys
    for mk, mapped in MANUAL_MAP.items():
        if mk in s or s in mk:
            return mapped

    return None


